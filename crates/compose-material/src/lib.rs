//! 留在核心 crate `compose::material`，本 crate 只持有 **composable 控件**。
//!
//! ```ignore
//! use compose::prelude::*;
//! use compose_material::{Button, Text};
//!
//! Button(Modifier::new(), || {}, || {
//!     Text("Click me", TextStyle::new(), Modifier::new());
//! });
//! ```

