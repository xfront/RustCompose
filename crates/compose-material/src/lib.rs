// ── 输入路由反转注册（解开 render↔material 的循环依赖）─────────────────────
//
// 合并后 `compose::render::{kernel,host}` 不再编译期依赖本 crate，而是经
// `compose::input_router` 的函数指针表转发键盘/字符/IME/剪贴板/滚动事件。
// app bootstrap 在启动事件循环前调一次 [`install_router`]，把本 crate 的 13 个
// `Input*` / `SetShiftState` 自由函数登记进去；未登记时核心转发安全退化为 no-op。

static INPUT_HANDLERS: compose::input_router::Handlers = compose::input_router::Handlers {
    focused: crate::InputFocused,
    char: crate::InputChar,
    backspace: crate::InputBackspace,
    key: crate::InputKey,
    commit: crate::InputCommit,
    preedit: crate::InputPreedit,
    enter: crate::InputEnter,
    copy: crate::InputCopy,
    cut: crate::InputCut,
    paste: crate::InputPaste,
    select_all: crate::InputSelectAll,
    shift: crate::SetShiftState,
    scroll: crate::InputScroll,
};

/// 把本 crate 的输入处理函数登记到核心的输入路由表（app 启动前调用一次）。
pub fn install_router() {
    compose::input_router::install(&INPUT_HANDLERS);
}
